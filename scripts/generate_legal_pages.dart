import 'dart:convert';
import 'dart:io';

import 'package:markdown/markdown.dart' as markdown;
import 'package:sqlite3/sqlite3.dart';

void main(List<String> args) {
  final check = args.length == 1 && args.single == '--check';
  if (args.isNotEmpty && !check) {
    stderr.writeln(
      'Usage: dart run scripts/generate_legal_pages.dart [--check]',
    );
    exitCode = 64;
    return;
  }

  final db = sqlite3.open(
    'web/db/revelation_en.sqlite',
    mode: OpenMode.readOnly,
  );
  try {
    for (final (route, fileName) in [
      ('privacy_policy', 'privacy-policy.html'),
      ('license', 'license.html'),
    ]) {
      final row = db.select(
        'SELECT name, description, markdown FROM articles WHERE route = ?',
        [route],
      ).single;
      final page = _renderPage(row);
      final file = File('web/$fileName');
      if (check) {
        if (!file.existsSync() ||
            file.readAsStringSync().replaceAll('\r\n', '\n') != page) {
          stderr.writeln('${file.path} differs from the English article.');
          exitCode = 1;
        }
      } else {
        file.writeAsStringSync(page);
      }
    }
  } finally {
    db.dispose();
  }
}

String _renderPage(Row row) {
  final name = const HtmlEscape().convert(row['name'] as String);
  final description = const HtmlEscape().convert(row['description'] as String);
  final body = markdown
      .markdownToHtml(
        row['markdown'] as String,
        extensionSet: markdown.ExtensionSet.gitHubFlavored,
      )
      .trimRight();
  return '''<!doctype html>
<!-- Generated by scripts/generate_legal_pages.dart from the English app database. -->
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="description" content="$description">
  <meta name="theme-color" content="#fff9ee">
  <title>$name | Revelation</title>
  <link rel="icon" href="favicon.png">
  <link rel="stylesheet" href="legal.css">
</head>
<body>
  <header class="app-bar">
    <a class="back-link" href="./" aria-label="Back to Revelation">&#8592;</a>
    <div>
      <h1 class="app-bar-title">$name</h1>
      <p class="app-bar-description">$description</p>
    </div>
  </header>
  <main class="document">
$body
  </main>
</body>
</html>
''';
}
